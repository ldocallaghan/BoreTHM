"""Generate the four packaged site files from their Python definitions.

Run from a source checkout with BoreTHM installed. --output selects a separate
directory for checking the generated files without changing the checkout.
"""
import argparse
from dataclasses import fields
import json
from pathlib import Path

import numpy as np

from borethm import comparative_sites as cs
from borethm import crosscheck_newberry as nb


DESTINATION = Path(__file__).resolve().parents[1] / 'src/borethm/templates/sites'


def _value(value):
    if isinstance(value, np.generic):
        value = value.item()
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (tuple, list)):
        return '[' + ', '.join(_value(item) for item in value) + ']'
    raise TypeError(f'unsupported site-file value: {type(value).__name__}')


def _assignment(name, value):
    return f'{name} = {_value(value)}'


def _geotherm_record(segments=None):
    if segments is not None:
        return dict(form='segments', boundary='below', segments=segments)
    return dict(form='points', gradient_below=nb.GRAD_DEEP,
                points=list(zip(nb.ST_TVD * nb.FT, nb.ST_T)))


def _capture(site, definition, segments, corrected_segments=None, stress_rule=None):
    rows = [
        f'# {site.name}',
        f'# Generated by tools/build_site_files.py from borethm.comparative_sites.{definition}.',
        '# Snapshot of the built-in inputs in the generation environment.',
        '# Recomputed numerical fits can differ in their last digits across platforms.',
        '# Edit a copy for your site; regenerate this file from the Python definition.',
        '# Units: depths m; temperatures C; gradients Pa/m or C/m as named;',
        '# stresses and strengths Pa; conductivity W/(m K); ratios dimensionless.',
        '# Stress and pore pressure use gauge values relative to 0.1 MPa absolute.',
    ]
    if segments is not None:
        rows += ['# Geotherm tables: borethm.comparative_sites.make_geotherm.']
    else:
        rows += [
            '# Temperature points: borethm.crosscheck_newberry.geotherm, static survey in TVD.',
            '# Deep gradient: numpy.polyfit on the deepest 1,500 ft of that survey,',
            '# as defined in borethm.crosscheck_newberry.GRAD_DEEP.',
            '# Target depth: borethm.crosscheck_newberry.target_depth.',
            '# Stress cases and Sv_grad: borethm.crosscheck_newberry.profile.',
            '# Pore-pressure fit: borethm.crosscheck_newberry.pore_pressure_fit.',
            '# Strength cases: borethm.crosscheck_newberry.granodiorite_strengths.',
        ]
    if stress_rule is not None:
        rows += ['# Stress cases: borethm.site_evaluation.transitional_bounds.']
    if definition == 'CORNWALL':
        rows += ['# Corrected target depth: 5000 + (400 - 180) / 0.028 in the CORNWALL definition.']
    data = {}
    tables = {'geotherm', 'geotherm_v11', 'stress_cases', 'data_basis'}
    for field in fields(site):
        value = getattr(site, field.name)
        if field.name not in tables and value is not None:
            data[field.name] = value
    data['geotherm'] = _geotherm_record(segments)
    if corrected_segments is not None:
        data['geotherm_v11'] = _geotherm_record(corrected_segments)
    if stress_rule is not None:
        data['stress_rule'] = dict(form='transitional', **stress_rule)
    else:
        data['stress_cases'] = [
            {field.name: getattr(case, field.name) for field in fields(case)
             if getattr(case, field.name) is not None}
            for case in site.stress_cases]
    data['data_basis'] = site.data_basis
    # Detach the record from mutable definitions and NumPy scalar types.
    return json.loads(json.dumps(dict(header=rows, data=data), default=lambda value: value.item()))


def render_record(record):
    """Format captured data without recomputing its derivation."""
    rows = [*record['header'], '']
    data = record['data']
    tables = {'geotherm', 'geotherm_v11', 'stress_rule', 'stress_cases', 'data_basis'}
    rows += [_assignment(name, value) for name, value in data.items() if name not in tables]
    for name in ('geotherm', 'geotherm_v11'):
        if name not in data:
            continue
        table = data[name]
        array = 'segments' if table['form'] == 'segments' else 'points'
        rows += ['', f'[{name}]']
        rows += [_assignment(key, value) for key, value in table.items() if key != array]
        rows += [array + ' = [', *('    ' + _value(row) + ',' for row in table[array]), ']']
    if 'stress_rule' in data:
        rows += ['', '[stress_rule]']
        rows += [_assignment(name, value) for name, value in data['stress_rule'].items()]
    for case in data.get('stress_cases', []):
        rows += ['', '[[stress_cases]]']
        rows += [_assignment(name, value) for name, value in case.items()]
    rows += ['', '[data_basis]']
    rows += [_assignment(_value(name), pair) for name, pair in data['data_basis'].items()]
    return '\n'.join(rows) + '\n'


def capture_sites():
    """Capture the current Python inputs and geotherm data before formatting."""
    return {
        'larderello.toml': _capture(cs.LARDERELLO, 'LARDERELLO', cs.LARDERELLO_GEOTHERM_SEGMENTS,
                                  cs.LARDERELLO_GEOTHERM_V11_SEGMENTS, cs.LARDERELLO_STRESS_RULE),
        'united-downs.toml': _capture(cs.CORNWALL, 'CORNWALL', cs.CORNWALL_GEOTHERM_SEGMENTS,
                                    cs.CORNWALL_GEOTHERM_V11_SEGMENTS),
        'pannonian.toml': _capture(cs.PANNONIAN, 'PANNONIAN', cs.PANNONIAN_GEOTHERM_SEGMENTS,
                                 stress_rule=cs.PANNONIAN_STRESS_RULE),
        'newberry.toml': _capture(cs.NEWBERRY, 'NEWBERRY', None),
    }


def render():
    """Return TOML files from a fresh capture of the Python definitions."""
    return {name: render_record(record) for name, record in capture_sites().items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=DESTINATION,
                        help='directory for the generated TOML files')
    arguments = parser.parse_args()
    arguments.output.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (arguments.output / name).write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
